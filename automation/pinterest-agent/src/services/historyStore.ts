// Reads

export interface QueryRangeOpts {
  startKey?: string; // inclusive
  endKey?: string; // inclusive
  limit?: number;
  scanForward?: boolean; // default true (ascending)
}

export async function queryRange<T = Record<string, unknown>>(
  entityType: EntityType,
  opts: QueryRangeOpts = {}
): Promise<T[]> {
  const { startKey, endKey, limit, scanForward = true } = opts;

  const exprNames: Record<string, string> = { "#et": "EntityType" };
  const exprValues: Record<string, unknown> = { ":et": entityType };
  let keyExpr = "#et = :et";

  if (startKey !== undefined && endKey !== undefined) {
    keyExpr += " AND #sk BETWEEN :a AND :b";
    exprNames["#sk"] = "SortKey";
    exprValues[":a"] = startKey;
    exprValues[":b"] = endKey;
  } else if (startKey !== undefined) {
    keyExpr += " AND #sk >= :a";
    exprNames["#sk"] = "SortKey";
    exprValues[":a"] = startKey;
  } else if (endKey !== undefined) {
    keyExpr += " AND #sk <= :b";
    exprNames["#sk"] = "SortKey";
    exprValues[":b"] = endKey;
  }

  const items: T[] = [];
  let exclusiveStartKey: Record<string, unknown> | undefined;

  do {
    const res = await ddb.send(
      new QueryCommand({
        TableName: TABLE,
        KeyConditionExpression: keyExpr,
        ExpressionAttributeNames: exprNames,
        ExpressionAttributeValues: exprValues,
        ScanIndexForward: scanForward,
        ExclusiveStartKey: exclusiveStartKey,
        Limit: limit !== undefined ? limit - items.length : undefined,
      })
    );
    if (res.Items) items.push(...(res.Items as T[]));
    exclusiveStartKey = res.LastEvaluatedKey;
    if (limit !== undefined && items.length >= limit) break;
  } while (exclusiveStartKey);

  return limit !== undefined ? items.slice(0, limit) : items;
}
