// Batch writes (DDB caps BatchWriteItem at 25 items per call).

async function batchPutRows(items: Record<string, unknown>[]): Promise<void> {
  for (let i = 0; i < items.length; i += 25) {
    const chunk = items.slice(i, i + 25);
    let requestItems: Record<string, { PutRequest: { Item: Record<string, unknown> } }[]> | undefined = {
      [TABLE]: chunk.map((Item) => ({ PutRequest: { Item } })),
    };
    while (requestItems && Object.keys(requestItems).length > 0) {
      const res: BatchWriteCommandOutput = await ddb.send(
        new BatchWriteCommand({ RequestItems: requestItems }),
      );
      const unprocessed = res.UnprocessedItems;
      requestItems =
        unprocessed && Object.keys(unprocessed).length > 0
          ? (unprocessed as typeof requestItems)
          : undefined;
    }
  }
}

