// Sort-key construction. Centralized so callers and queryRange agree.
function padDesignId(designId: number): string {
  return designId.toString().padStart(5, "0");
}

export const sortKey = {
  pinterestToken: () => "CURRENT" as const,
  dailyBusiness: (date: string) => date,
  aiAnalysis: (generatedAt: string, type: AnalysisType) =>
    `${generatedAt}#${type}`,
  designPinMap: (designId: number) => padDesignId(designId),
  designPerformance: (snapshotDate: string, designId: number) =>
    `${snapshotDate}#${padDesignId(designId)}`,
  anomalyEvent: (detectedAt: string, metric: AnomalyMetric) =>
    `${detectedAt}#${metric}`,
  promotedAdStats: (date: string, adId: string) => `${date}#${adId}`,
  landingPageStats: (date: string, page: string) => `${date}#${page}`,
  pinAttribution: (date: string, adId: string) => `${date}#${adId}`,
  blockedIp: (ip: string) => ip,
  watchedIp: (ip: string) => ip,
};

